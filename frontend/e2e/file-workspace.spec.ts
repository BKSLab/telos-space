import { expect, test } from "@playwright/test";
import { installProjectFilesApi, projectFile } from "./support/projectFilesMockApi";

for (const width of [1440, 390, 320]) {
    test(`единая карточка, комментарий, клавиатура и компактный список ${width}px`, async ({ page }, testInfo) => {
        test.setTimeout(60_000);
        await page.setViewportSize({ width, height: 900 });
        const name = "Очень-длинное-название-схемы-проекта-без-пробелов-для-проверки-переносов.png";
        const state = await installProjectFilesApi(page, [
            projectFile({ original_name: name, content_type: "image/png", previewable: true, preview_url: "/api/v1/projects/1/files/5/preview", extraction_status: "disabled", index_status: "disabled" }),
            projectFile({ id: 6, original_name: "Исходные данные.txt", content_type: "text/plain", extraction_status: "processing", index_status: "pending" }),
            projectFile({ id: 7, original_name: "Решение.md", content_type: "text/markdown", extraction_status: "failed", index_status: "disabled" }),
        ]);
        state.originals.set(6, "Исходный TXT 🪐\n\n  Отступ\nВторая строка");
        state.originals.set(7, "# Решение 🛰️\n\n**Согласовано**\n\n| Поле | Значение |\n| --- | --- |\n| Срок | Сегодня |");
        await page.goto("/projects/DEMO/docs");
        const list = page.getByRole("list", { name: "Файлы проекта", exact: true });
        await expect(list.getByRole("listitem")).toHaveCount(3);
        await expect(list.getByText("План запуска проекта", { exact: true })).toHaveCount(0);
        await expect(list.getByRole("link")).toHaveCount(0);
        const row = list.getByRole("button", { name: `Открыть файл ${name}`, exact: true });
        expect((await row.boundingBox())!.height).toBeLessThanOrEqual(76);
        await page.screenshot({ path: testInfo.outputPath(`files-list-${width}.png`) });
        await row.focus();
        await page.keyboard.press("Enter");
        const dialog = page.getByRole("dialog", { name, exact: true });
        await expect(dialog.getByRole("tab", { name: "Документ", exact: true })).toHaveAttribute("aria-selected", "true");
        await expect.poll(() => dialog.getByAltText(name).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
        await expect(dialog.getByText("Загрузил: Тестов Тест", { exact: true })).toBeVisible();
        await expect(dialog.locator("time")).toHaveAttribute("datetime", state.files[0].created_at);
        await expect(dialog.locator("time")).toContainText("2026");
        await expect(dialog.getByRole("link", { name: "Скачать оригинал" })).toBeVisible();
        expect(new URL(page.url()).searchParams.get("file")).toBe("5");
        await page.screenshot({ path: testInfo.outputPath(`file-image-${width}.png`) });
        await dialog.getByRole("tab", { name: "Документ", exact: true }).focus();
        await page.keyboard.press("ArrowRight");
        await expect(dialog.getByRole("tab", { name: "Текстовое представление" })).toHaveAttribute("aria-selected", "true");
        await expect(dialog.getByRole("tabpanel", { name: "Текстовое представление" })).toContainText("Распознавание изображения отключено");
        await page.keyboard.press("ArrowLeft");
        await dialog.getByRole("button", { name: "Добавить комментарий" }).click();
        const comment = dialog.getByRole("textbox", { name: "Комментарий к файлу" });
        await expect(comment).toBeFocused();
        await comment.fill("Согласовано с командой\nВторая строка 🪐");
        state.captionError = true;
        await dialog.getByRole("button", { name: "Сохранить комментарий" }).click();
        await expect(dialog.getByRole("alert")).toContainText("Не удалось сохранить комментарий");
        await expect(comment).toHaveValue("Согласовано с командой\nВторая строка 🪐");
        await dialog.getByRole("tab", { name: "Текстовое представление" }).click();
        await dialog.getByRole("tab", { name: "Документ", exact: true }).click();
        await expect(comment).toHaveValue("Согласовано с командой\nВторая строка 🪐");
        state.captionError = false;
        await dialog.getByRole("button", { name: "Сохранить комментарий" }).click();
        await expect(dialog.getByRole("button", { name: "Изменить комментарий" })).toBeVisible();
        await dialog.getByRole("button", { name: "Изменить комментарий" }).click();
        await comment.fill("Отменённый черновик");
        await dialog.getByRole("button", { name: "Отмена", exact: true }).click();
        expect(state.files[0].caption).toBe("Согласовано с командой\nВторая строка 🪐");
        await page.screenshot({ path: testInfo.outputPath(`file-comment-${width}.png`) });
        await page.keyboard.press("Escape");
        await expect(dialog).toHaveCount(0);
        await expect(row).toBeFocused();
        await page.keyboard.press("Space");
        await expect(dialog.getByText(/Согласовано с командой/)).toBeVisible();
        await page.keyboard.press("Escape");
        await list.getByRole("button", { name: "Открыть файл Исходные данные.txt" }).click();
        const txt = page.getByRole("dialog", { name: "Исходные данные.txt", exact: true });
        await expect(txt.getByRole("region", { name: "Содержимое оригинала" })).toContainText("Исходный TXT 🪐");
        await expect(txt.locator("pre")).toHaveText(state.originals.get(6)!);
        await page.keyboard.press("Escape");
        await list.getByRole("button", { name: "Открыть файл Решение.md" }).click();
        const markdown = page.getByRole("dialog", { name: "Решение.md", exact: true });
        await expect(markdown.getByRole("heading", { name: "Решение 🛰️" })).toBeVisible();
        await expect(markdown.getByRole("table")).toBeVisible();
        await page.screenshot({ path: testInfo.outputPath(`file-markdown-${width}.png`) });
        expect(await markdown.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
        await page.keyboard.press("Escape");
        await page.getByLabel("Поиск документов и файлов проекта").fill("Решение.md");
        await page.getByRole("list", { name: "Результаты поиска файлов" }).getByRole("button", { name: "Открыть файл Решение.md" }).click();
        await expect(markdown.getByRole("heading", { name: "Решение 🛰️" })).toBeVisible();
        expect(state.requests.filter(request => request.url.pathname.endsWith("/retry"))).toHaveLength(0);
        expect(state.errors).toEqual([]);
    });

    test(`права, ошибки оригинала и изображения, предел просмотра ${width}px`, async ({ page }, testInfo) => {
        test.setTimeout(60_000);
        await page.setViewportSize({ width, height: 900 });
        const state = await installProjectFilesApi(page, [projectFile({ original_name: "Текст.txt", content_type: "text/plain", uploaded_by_name: null })]);
        state.canEdit = false;
        state.originalError = true;
        state.originals.set(5, "Полный оригинал после повтора");
        await page.goto("/projects/DEMO/docs?file=5");
        let dialog = page.getByRole("dialog", { name: "Текст.txt", exact: true });
        await expect(dialog.getByText("Загрузил: Автор недоступен", { exact: true })).toBeVisible();
        await expect(dialog.getByRole("button", { name: "Добавить комментарий" })).toHaveCount(0);
        await expect(dialog.getByRole("button", { name: "Удалить", exact: true })).toHaveCount(0);
        await expect(dialog.getByRole("button", { name: "Повторить обработку", exact: true })).toHaveCount(0);
        await expect(dialog.getByRole("alert")).toContainText("Оригинал временно недоступен");
        state.originalError = false;
        await dialog.getByRole("button", { name: "Повторить загрузку оригинала" }).click();
        await expect(dialog.getByRole("region", { name: "Содержимое оригинала" }).locator("pre")).toHaveText(state.originals.get(5)!);
        await page.keyboard.press("Escape");
        await expect(dialog).toHaveCount(0);
        await expect.poll(() => new URL(page.url()).searchParams.has("file")).toBe(false);
        Object.assign(state.files[0], { original_name: "Большой.txt", size: 1024 * 1024 + 1 });
        await page.reload();
        await page.getByRole("button", { name: "Открыть файл Большой.txt" }).click();
        dialog = page.getByRole("dialog", { name: "Большой.txt", exact: true });
        await expect(dialog.getByText(/Файл больше 1 МБ/)).toBeVisible();
        await expect(dialog.getByRole("link", { name: "Скачать оригинал" })).toBeVisible();
        await page.keyboard.press("Escape");
        await expect(dialog).toHaveCount(0);
        await expect.poll(() => new URL(page.url()).searchParams.has("file")).toBe(false);
        Object.assign(state.files[0], { original_name: "Фото.png", content_type: "image/png", previewable: true, preview_url: "/api/v1/projects/1/files/5/preview", extraction_status: "empty", index_status: "disabled" });
        state.previewError = true;
        await page.reload();
        await page.getByRole("button", { name: "Открыть файл Фото.png" }).click();
        dialog = page.getByRole("dialog", { name: "Фото.png", exact: true });
        await expect(dialog.getByRole("alert")).toContainText("Не удалось загрузить изображение");
        state.previewError = false;
        await dialog.getByRole("button", { name: "Загрузить изображение снова" }).click();
        await expect.poll(() => dialog.locator("img").evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
        await dialog.getByRole("tab", { name: "Текстовое представление" }).click();
        await expect(dialog.getByText(/Извлечённого текста нет/)).toBeVisible();
        await page.screenshot({ path: testInfo.outputPath(`file-states-${width}.png`) });
        expect(state.requests.filter(request => ["POST", "PATCH", "DELETE"].includes(request.method))).toHaveLength(0);
        expect(state.errors).toEqual([]);
    });

    test(`внутренний Markdown сохраняет создание и редактирование ${width}px`, async ({ page }) => {
        await page.setViewportSize({ width, height: 900 });
        const state = await installProjectFilesApi(page);
        await page.goto("/projects/DEMO/docs");
        await page.getByRole("button", { name: "Документ", exact: true }).click();
        const create = page.getByRole("dialog", { name: "Новый документ", exact: true });
        await create.getByLabel("Заголовок").fill("План пилота");
        await create.getByRole("button", { name: "Создать", exact: true }).click();
        await page.getByRole("link", { name: /План пилота/ }).click();
        await expect(page.getByRole("heading", { name: "План пилота", exact: true }).first()).toBeVisible();
        await page.getByRole("button", { name: "Редактировать документ" }).click();
        await page.getByLabel("Содержимое документа в Markdown").fill("# Проверенный план\n\n**Решение сохранено** 🪐");
        await page.getByRole("button", { name: "Сохранить", exact: true }).click();
        await expect(page.getByRole("heading", { name: "Проверенный план", exact: true })).toBeVisible();
        expect(state.document.content_md).toContain("Решение сохранено");
        expect(state.errors).toEqual([]);
    });
}
